function doc(
  id: string,
  name: string,
  typeCode: string,
  typeName: string,
  category: StoredDocument["category"],
  linkedType: StoredDocument["linkedType"],
  linkedId: string,
  ownerOrgId: string,
  uploadedById: string,
  uploadedByName: string,
  uploadedAt: string,
  extra: Partial<StoredDocument> = {},
  sizeBytes = 131072,
  mimeType = "application/pdf",
): StoredDocument {
  return {
    id,
    name,
    typeCode,
    typeName,
    category,
    status: "verified",
    visibility: "customer",
    ownerOrgId,
    linkedType,
    linkedId,
    issueDate: uploadedAt.slice(0, 10),
    expiryDate: null,
    rejectionReason: null,
    verifiedById: USER.dante,
    verifiedAt: uploadedAt,
    createdAt: uploadedAt,
    updatedAt: uploadedAt,
    versions: [
      {
        versionNo: 1,
        fileName: name,
        storedPath: null,
        sizeBytes,
        mimeType,
        uploadedById,
        uploadedByName,
        uploadedAt,
      },
    ],
    ...extra,
  };
}

